export function actionsForDomain(domain: AuditDomain): AuditActionCode[] {
  return (Object.entries(AUDIT_ACTION_DOMAIN) as [AuditActionCode, AuditDomain][])
    .filter(([, mapped]) => mapped === domain)
    .map(([action]) => action);
}

export function isSensitiveAuditAction(action: string): boolean {
  return (SENSITIVE_AUDIT_ACTIONS as readonly string[]).includes(action);
}
